  /** Paramètres PS d'un code OACI (le code lui-même, sinon son équivalent dans la liste des synonymes) ; null sinon. */
  const typeOf = icao => {
    const k = String(icao || '').toUpperCase().trim();
    return PS[k] ? k : PS[SYN[k]] ? SYN[k] : null;
  };
  /** Atmosphère standard : température (K) et pression (Pa) à l'altitude h (m). */
  function isa(h) {
    if (h <= 11000) {
      const t = 288.15 - 0.0065 * h;
      return {
        t,
        p: 101325 * Math.pow(t / 288.15, G / (0.0065 * R_D))
      };
    }
    const p11 = 101325 * Math.pow(216.65 / 288.15, G / (0.0065 * R_D));
    return {
      t: 216.65,
      p: p11 * Math.exp(-G * (h - 11000) / (R_D * 216.65))
    };
  }
  /** Rendement propulsif rapporté au rendement maximal à ce Mach (polynôme du modèle, eq. 4 de la partie 2). */
  function etaRatio(mach, x) {
    let s = -0.43,
      p = 0;
    if (mach < 0.4) {
      const sigma = 1.3 * (0.4 - mach);
      s = sigma - 0.43;
      p = sigma * 0.43;
    }
    if (x < 0.3) {
      const a1 = 10 * (1 + 0.8 * s - 0.6027 * p),
        a2 = 33.3333 * (-1 - 0.97 * s + 0.8281 * p),
        a3 = 37.037 * (1 + s - 0.9163 * p);
      return x * (a1 + x * (a2 + x * a3));
    }
    return (1 + s - p) + x * ((4 * p - 2 * s) + x * ((s - 6 * p) + x * (4 * p + x * -p)));
  }
  /** Consommation de croisière (kg/h, avion entier) du type icao à la masse massKg, à l'altitude altitudeFt et au Mach
   *  mach (défauts : masse moyenne entre MZFW et MTOW, FL350, Mach de conception) ; null si le type n'est pas couvert. */
  function fuelFlowKgh(icao, {
    massKg,
    altitudeFt,
    mach
  } = {}) {
    const k = typeOf(icao);
    if (!k) return null;
    const a = PS[k],
      m = Math.min(+mach || a.mDes, a.mmo),
      mass = +massKg || (a.mzfw + a.mtow) / 2,
      ft = Number.isFinite(+altitudeFt) && altitudeFt !== '' && altitudeFt != null ? +altitudeFt : 35000,
      {
        t,
        p
      } = isa(ft * 0.3048),
      S = a.s;
    // portance, traînée (frottement, induite, d'onde) et poussée en palier
    const mu = 1.458e-6 * Math.pow(t, 1.5) / (110.4 + t),
      rn = Math.sqrt(S) * m * (p / mu) * Math.sqrt(KAPPA / (R_D * t)),
      cl = mass * G / ((KAPPA / 2) * p * m * m * S),
      cd0 = 0.0269 / Math.pow(rn, 0.14) * a.psi0,
      k1 = 0.8 * (1 - 0.53 * a.cosSweep) * cd0,
      e = (a.winglets ? 1.075 : 1) / (1 + 0.03 + a.delta2 + k1 * Math.PI * a.ar),
      mcc = a.wingK - 0.1 * (cl / (a.cosSweep * a.cosSweep)),
      x = m * a.cosSweep / mcc,
      dj = Math.max(x - a.j2, 0),
      dr = Math.max(x - a.xRef, 0),
      cdw = Math.pow(a.cosSweep, 3) * a.j1 * dj * dj + 70 * dr * dr * dr * dr,
      cd = cd0 + cl * cl / (Math.PI * a.ar * e) + cdw,
      thrust = mass * G * cd / cl,
      ct = thrust / (0.5 * KAPPA * p * m * m * S),
      ctb = ((1 + 0.55 * m) / (1 + 0.55 * a.mDes)) / Math.pow(m / a.mDes, 2) * a.ctDes;
    // rendement propulsif global, puis débit de carburant
    const ratio = Math.max(etaRatio(m, ct / ctb), ETA_RATIO_MIN),
      eta = ratio * (a.eta1 / (1 + DETERIORATION)) * Math.pow(m, a.eta2),
      ff = (KAPPA / 2) * (ct * m * m * m / eta) * Math.sqrt(KAPPA * R_D * t) * p * S / Q_FUEL;
    // bornes : ralenti de vol, débit maximal ramené aux conditions de croisière
    const h4 = ft / 10000,
      ffMin = a.ffIdle * (1 - 0.178 * h4 + 0.0085 * h4 * h4),
      ffMax = a.ffMax / Math.max(1, Math.pow(t / 288.15, 3.8) / (p / 101325) * Math.exp(0.2 * m * m));
    return Math.round(Math.min(Math.max(ff, ffMin), ffMax) * 3600);
  }
